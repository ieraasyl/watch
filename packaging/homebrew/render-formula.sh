#!/usr/bin/env bash
# Print the Homebrew formula for a published release.
# Usage: render-formula.sh <version> <SHA256SUMS file>
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "Usage: $0 <version> <SHA256SUMS file>" >&2
  exit 2
fi
version=$1
sums=$2
if [[ ! "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "Version must look like 1.2.3, not $version" >&2
  exit 1
fi

checksum() {
  local asset="wvd-$1.tar.gz" sum
  sum=$(awk -v asset="$asset" '$2 == asset || $2 == "*" asset { print $1 }' "$sums")
  if [[ ! "$sum" =~ ^[0-9a-f]{64}$ ]]; then
    echo "Missing or invalid checksum for $asset in $sums" >&2
    exit 1
  fi
  printf '%s' "$sum"
}

base="https://github.com/ieraasyl/wvd/releases/download/v$version"
macos_arm64=$(checksum macos-arm64)
macos_x86_64=$(checksum macos-x86_64)
linux_arm64=$(checksum linux-arm64)
linux_x86_64=$(checksum linux-x86_64)

cat <<FORMULA
# Generated by packaging/homebrew/render-formula.sh in ieraasyl/wvd. Do not edit.
class Wvd < Formula
  desc "Browse and resume your local media library from the terminal"
  homepage "https://github.com/ieraasyl/wvd"
  license "MIT"

  on_macos do
    depends_on "mpv"

    on_arm do
      url "$base/wvd-macos-arm64.tar.gz"
      sha256 "$macos_arm64"
    end
    on_intel do
      url "$base/wvd-macos-x86_64.tar.gz"
      sha256 "$macos_x86_64"
    end
  end

  on_linux do
    on_arm do
      url "$base/wvd-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/wvd-linux-x86_64.tar.gz"
      sha256 "$linux_x86_64"
    end
  end

  def install
    bin.install "wvd"
  end

  def caveats
    on_linux do
      <<~EOS
        wvd plays videos with mpv. Install it with your distribution's package manager.
      EOS
    end
  end

  test do
    assert_equal "wvd #{version}", shell_output("#{bin}/wvd --version").strip
    (testpath/"config.toml").write ""
    (testpath/"media").mkpath
    touch testpath/"media/Show - 01.mkv"
    output = shell_output(
      "#{bin}/wvd --config #{testpath}/config.toml --data-dir #{testpath}/history " \\
      "--root #{testpath}/media list",
    )
    assert_match "Episode 01  [Unwatched]", output
  end
end
FORMULA
